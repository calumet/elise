/** El hueco de una entrada mientras carga, con ancho variable para que no parezca una grilla. */
function SidebarMenuSkeleton({
  className,
  showIcon = false,
  ...props
}: React.ComponentProps<"div"> & {
  showIcon?: boolean;
}): React.JSX.Element {
  // El ancho varía para que la lista no parezca una grilla, y sale del `id`
  // porque en SSR tiene que dar lo mismo en el servidor y en el cliente.
  const id = React.useId();
  let sum = 0;
  for (const c of id) sum += c.charCodeAt(0);
  const width = `${(sum % 41) + 50}%`;

  return (
    <div
      data-slot="sidebar-menu-skeleton"
      data-sidebar="menu-skeleton"
      className={cn("flex h-8 items-center gap-2 rounded-md px-2", className)}
      {...props}
    >
      {showIcon && (
        <Skeleton className="size-icon-md rounded-md" data-sidebar="menu-skeleton-icon" />
      )}
      <Skeleton
        className="h-4 max-w-(--skeleton-width) flex-1"
        data-sidebar="menu-skeleton-text"
        style={
          {
            "--skeleton-width": width,
          } as React.CSSProperties
        }
      />
    </div>
  );
}

