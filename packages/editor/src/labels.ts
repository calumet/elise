export type Labels = Record<keyof typeof DEFAULTS, string>;

export const typeLabel = (t: Labels, type: string): string =>
  ({
    p: t.paragraph,
    h2: t.heading2,
    h3: t.heading3,
    blockquote: t.quote,
    callout: t.callout,
    hr: t.divider,
    img: t.image,
    media_embed: t.video,
    table: t.table,
    columns: t.columns,
    column: t.column,
    spacer: t.spacer,
    button: t.buttonBlock,
    gallery: t.gallery,
    file: t.file,
  })[type] ?? type;

export const useLabels = (): Labels => {
  const translate = useElTranslate("editor");
  return Object.fromEntries(
    Object.entries(DEFAULTS).map(([key, fallback]) => [key, translate(key, fallback)]),
  ) as Labels;
};
